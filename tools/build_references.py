"""Regenerate the bundled reference files from SailPoint's public, MIT-licensed sources.

Usage:
    git clone --depth 1 https://github.com/sailpoint-oss/api-specs.git /tmp/api-specs
    git clone --depth 1 --filter=blob:none --sparse \
        https://github.com/sailpoint-oss/developer.sailpoint.com.git /tmp/dev-docs
    (cd /tmp/dev-docs && git sparse-checkout set docs)
    python3 tools/build_references.py --specs /tmp/api-specs --docs /tmp/dev-docs

Only the files under skills/*/references/ that this script owns are rewritten
(they start with the GENERATED banner). Hand-written references are left alone.
"""
from __future__ import annotations

