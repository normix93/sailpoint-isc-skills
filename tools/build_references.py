import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
DEV = "https://developer.sailpoint.com"

BANNER = (
    "<!-- GENERATED by tools/build_references.py from {src} (commit {sha}, {date}). "
    "Do not edit by hand: re-run the script. Source content (c) SailPoint, MIT License. -->\n\n"
)


# --------------------------------------------------------------------------- helpers

def git_sha(path: Path) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(path), "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        return "unknown"


LEGACY_NOTE = ("> Paths in this page's examples may use the legacy `/beta`, `/v3` or `/v202x` prefixes. "
               "They still work until end of support; for new code use the per-service path from the isc-api skill "
               "(`references/versioning-map.md`), e.g. `/beta/connector-rules` -> `/connector-rules/v1`.\n\n")


def write(path: Path, text: str, src: str, sha: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    banner = BANNER.format(src=src, sha=sha, date=dt.date.today().isoformat())
    if src.startswith("developer.sailpoint.com") and re.search(r"/(beta|v3|v20\d\d)/", text):
        banner += LEGACY_NOTE
    path.write_text(banner + text.strip() + "\n", encoding="utf-8")


ADMONITION = re.compile(r"^:::\s*(\w+)\s*(.*)$")


def clean_md(raw: str, page_url: str | None = None) -> str:
    """Turn a Docusaurus page into plain Markdown an agent can read."""
    text = raw.replace("\r\n", "\n")
    title = None
    if text.startswith("---"):
        end = text.find("\n---", 3)
        front = text[3:end]
        m = re.search(r"^title:\s*['\"]?(.+?)['\"]?\s*$", front, re.M)
        title = m.group(1) if m else None
        text = text[end + 4:]
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    out: list[str] = []
    in_code = False
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("```"):
            if s.startswith("```mdx-code-block"):
                continue
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue
        if s.startswith("import ") or s.startswith("export "):
            continue
        if re.match(r"^</?(DocCardList|div|iframe|Tabs|TabItem|details|summary|p|br|center|img)\b", s):
            continue
        if s in ("<p>&nbsp;</p>", "&nbsp;"):
            continue
        m = ADMONITION.match(s)
        if m:
            kind, label = m.group(1), m.group(2)
            # one-line admonition ":::note Important text :::"
            if label.endswith(":::"):
                out.append(f"> **{kind.capitalize()}:** {label[:-3].strip()}")
            else:
                out.append(f"> **{(label or kind).strip().capitalize()}:**")
            continue
        if s == ":::":
            out.append("")
            continue
        # images are useless for an agent
        line = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", line)
        # absolute-ise site links
        line = re.sub(r"\]\((/(?:docs|tools|idn|api)[^)]*)\)", lambda mm: f"]({DEV}{mm.group(1)})", line)
        # relative .md links -> keep the label only (the target may not be bundled)
        line = re.sub(r"\[([^\]]+)\]\((?:\.\.?/)[^)]*\)", r"\1", line)
        out.append(line)
    body = "\n".join(out)
    body = re.sub(r"\n{3,}", "\n\n", body).strip()
    head = f"# {title}\n\n" if title else ""
    if page_url:
        head += f"Source: {page_url}\n\n"
    return head + body


def slug_of(path: Path) -> str:
    return path.stem.replace("_", "-")


def page_url(md: Path, docs_root: Path) -> str:
    raw = md.read_text(encoding="utf-8")
    m = re.search(r"^slug:\s*(\S+)", raw, re.M)
    if m:
        return f"{DEV}/docs{m.group(1)}" if not m.group(1).startswith("/docs") else DEV + m.group(1)
    return f"{DEV}/docs/{md.relative_to(docs_root).with_suffix('')}"


def copy_pages(files, dest: Path, docs_root: Path, sha: str, rename=None) -> list[tuple[str, str, str]]:
    index = []
    for f in sorted(files):
        raw = f.read_text(encoding="utf-8")
        title = re.search(r"^title:\s*['\"]?(.+?)['\"]?\s*$", raw, re.M)
        desc = re.search(r"^description:\s*['\"]?(.+?)['\"]?\s*$", raw, re.M)
        name = rename(f) if rename else slug_of(f)
        write(dest / f"{name}.md", clean_md(raw, page_url(f, docs_root)), "developer.sailpoint.com", sha)
        index.append((name, title.group(1) if title else name, desc.group(1) if desc else ""))
    return index


