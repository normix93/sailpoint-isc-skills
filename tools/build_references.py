def build_doc_refs(docs: Path) -> None:
    d = docs / "docs"
    sha = git_sha(docs)

    # transforms
    tr = d / "extensibility/transforms"
    dest = SKILLS / "isc-transforms/references"
    ops = copy_pages([p for p in (tr / "operations").glob("*.md") if p.name != "index.md"], dest / "operations", d, sha)
    copy_pages([tr / "index.md"], dest, d, sha, rename=lambda f: "transforms-overview")
    copy_pages([p for p in (tr / "guides").glob("*.md") if p.name != "index.md"], dest / "guides", d, sha)
    copy_pages([p for p in (tr / "out-of-the-box-operations").glob("*.md") if p.name != "index.md"], dest / "guides", d, sha)
    rows = "\n".join(f"| `{n}` | {t} | {s} |" for n, t, s in ops)
    write(dest / "operations-index.md",
          "# Transform operations index\n\nOne file per operation in `operations/`.\n\n"
          "| File | Operation | What it does |\n|---|---|---|\n" + rows, "developer.sailpoint.com", sha)

    build_transform_types(tr / "operations", SKILLS / "isc-transforms/scripts/transform_types.json", sha)

    # rules
    ru = d / "extensibility/rules"
    build_forbidden_tokens(ru / "index.md", SKILLS / "isc-rules/scripts/forbidden_tokens.json", sha)
    dest = SKILLS / "isc-rules/references"
    cloud = copy_pages([p for p in (ru / "cloud-rules").glob("*.md") if p.name != "index.md"], dest / "cloud", d, sha)
    conn = copy_pages([p for p in (ru / "connector-rules").glob("*.md") if p.name != "index.md"], dest / "connector", d, sha)
    copy_pages([ru / "index.md"], dest, d, sha, rename=lambda f: "rules-overview")
    copy_pages([ru / "cloud-rules/index.md"], dest, d, sha, rename=lambda f: "cloud-rules-process")
    copy_pages([ru / "connector-rules/index.md"], dest, d, sha, rename=lambda f: "connector-rules-process")
    copy_pages([ru / "idn_rule_utility.md"], dest, d, sha, rename=lambda f: "rule-utility")
    copy_pages([ru / "guides/your_first_rule.md"], dest, d, sha, rename=lambda f: "your-first-rule")

    # event triggers
    et = d / "extensibility/event-triggers"
    dest = SKILLS / "isc-event-triggers/references"
    trig = copy_pages(list((et / "available").glob("*.md")), dest / "triggers", d, sha)
    copy_pages([p for p in et.glob("*.md*") if p.name not in ("index.md",)], dest, d, sha,
               rename=lambda f: f.name.split(".")[0])
    rows = "\n".join(f"| `triggers/{n}.md` | {t} | {s} |" for n, t, s in trig)
    write(dest / "triggers-index.md", "# Trigger pages\n\n| File | Trigger | Fires when |\n|---|---|---|\n" + rows,
          "developer.sailpoint.com", sha)

    # api guides
    dest = SKILLS / "isc-api/references"
    for name in ["standard-collection-parameters", "patch-requests", "authentication", "authorization",
                 "rate-limit", "api-versioning-strategy"]:
        copy_pages([d / f"api/{name}.md"], dest / "guides", d, sha, rename=lambda f, n=name: n)
    build_version_map(d / "api/api-versioning-migration.md", dest / "versioning-map.md", sha)

    # search / audit events
    dest = SKILLS / "isc-search/references"
    copy_pages([d / "guides/searching-audit-events.md"], dest, d, sha, rename=lambda f: "audit-events-search")
    copy_pages([d / "guides/audit-events-reference.md"], dest, d, sha, rename=lambda f: "audit-events-reference")


ATTR_LINE = re.compile(r"^\s*- \*\*([A-Za-z0-9_.$]+)\*\*\s*`[^`]+`(?:\s*\|\s*`[^`]+`)*\s*_\((required|optional)\)_")


def build_transform_types(ops_dir: Path, dest: Path, sha: str) -> None:
    """Machine-readable map type -> required/optional attributes, used by validate_transform.py."""
    types: dict = {}
    rule_ops: dict = {}
    for f in sorted(ops_dir.glob("*.md")):
        if f.name == "index.md":
            continue
        raw = f.read_text(encoding="utf-8")
        m = re.search(r"Must be set to `([A-Za-z0-9]+)`", raw) or re.search(r'"type":\s*"([A-Za-z0-9]+)"', raw)
        if not m:
            continue
        ttype = m.group(1)
        body = raw.split("## Attributes", 1)[1] if "## Attributes" in raw else raw
        body = body.split("## Examples", 1)[0]
        if "### `attributes`" in body:          # skip the repeated top-level property list
            body = body.split("### `attributes`", 1)[1]
            skip = set()
        else:
            skip = {"type", "name", "requiresPeriodicRefresh"}
        req, opt = set(), set()
        for line in body.split("\n"):
            a = ATTR_LINE.match(line)
            if a and a.group(1) not in skip | {"attributes"}:
                (req if a.group(2) == "required" else opt).add(a.group(1))
        op = re.search(r'"operation":\s*"([A-Za-z0-9]+)"', raw)
        if ttype == "rule" and op:
            rule_ops[op.group(1)] = {"required": sorted(req - {"name", "operation"}),
                                     "optional": sorted(opt), "doc": f.stem}
            continue
        entry = types.setdefault(ttype, {"required": set(), "optional": set(), "doc": f.stem})
        entry["required"] |= req
        entry["optional"] |= opt
    out = {k: {"required": sorted(v["required"]), "optional": sorted(v["optional"] | {"input"}), "doc": v["doc"]}
           for k, v in types.items()}
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps({"_generated": f"tools/build_references.py from developer.sailpoint.com {sha}",
                                "types": out, "ruleOperations": rule_ops}, indent=1, sort_keys=True) + "\n")


def build_forbidden_tokens(src: Path, dest: Path, sha: str) -> None:
    raw = src.read_text(encoding="utf-8")
    sec = raw.split("## Rule code restrictions", 1)[1]
    block = re.search(r"```java\n(.*?)```", sec, re.S).group(1)
    tokens = sorted({t.strip().replace("​", "") for t in block.split("\n") if t.strip()})
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps({"_generated": f"tools/build_references.py from developer.sailpoint.com {sha}",
                                "source": f"{DEV}/docs/extensibility/rules#rule-code-restrictions",
                                "tokens": tokens}, indent=1) + "\n")


def build_version_map(src: Path, dest: Path, sha: str) -> None:
    rows = [l for l in src.read_text(encoding="utf-8").split("\n") if re.match(r"^\| `/", l)]
    text = ("# Legacy path -> per-service version map\n\n"
            "From SailPoint's API versioning migration guide. New URL = `/{service}/{New Version}/...`; "
            "legacy URL = `/{legacy}/{service}/...`.\n\n"
            "| Service | Legacy Versions | New Version |\n|---|---|---|\n" + "\n".join(rows))
    write(dest, text, "developer.sailpoint.com/docs/api/api-versioning-migration", sha)


# --------------------------------------------------------------------------- spec-based references

class Spec:
    def __init__(self, path: Path):
        self.d = json.loads(path.read_text(encoding="utf-8"))

    def res(self, o):
        seen = 0
        while isinstance(o, dict) and "$ref" in o and seen < 20:
            ref = o["$ref"]
            if not ref.startswith("#/"):
                return o
            cur = self.d
            for part in ref[2:].split("/"):
                cur = cur[part.replace("~1", "/").replace("~0", "~")]
            o = cur
            seen += 1
        return o

    def type_name(self, schema, depth=0) -> str:
        s = self.res(schema or {})
        if not isinstance(s, dict):
            return "?"
        ref = (schema or {}).get("$ref", "")
        name = ref.rsplit("/", 1)[-1] if ref else s.get("title")
        if s.get("type") == "array":
            return f"array of {self.type_name(s.get('items'), depth + 1)}"
        if name:
            return name
        return s.get("type", "object")

    def props(self, schema, depth=0) -> dict:
        s = self.res(schema or {})
        if not isinstance(s, dict) or depth > 4:
            return {}
        out = {}
        for key in ("allOf", "anyOf", "oneOf"):
            for part in s.get(key, []):
                out.update(self.props(part, depth + 1))
        out.update(s.get("properties", {}))
        return out


def short(text: str, n: int = 300) -> str:
    t = re.sub(r"\s+", " ", (text or "")).strip()
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "…"


def param_lines(spec: Spec, params) -> list[str]:
    lines = []
    for p in params:
        p = spec.res(p)
        if not isinstance(p, dict) or "name" not in p:
            continue
        name, where = p["name"], p.get("in")
        if name.lower() == "x-sailpoint-experimental":
            continue
        sch = spec.res(p.get("schema", {}))
        bits = [f"`{name}` ({where}{', required' if p.get('required') else ''})"]
        if isinstance(sch, dict):
            if "maximum" in sch:
                bits.append(f"max {sch['maximum']}")
            if "default" in sch:
                bits.append(f"default {sch['default']}")
            if sch.get("enum"):
                bits.append("one of " + ", ".join(str(e) for e in sch["enum"] if e is not None))
        desc = p.get("description", "")
        if name in ("filters", "sorters"):
            fields = re.findall(r"\*\*([\w.\-\[\]]+)\*\*:?\s*\*?([^*\n]*)\*?", desc)
            if name == "filters" and fields:
                bits.append("fields: " + "; ".join(f"{f}: {ops.strip(' ,')}" for f, ops in fields))
            elif name == "sorters":
                m = re.search(r"following fields:?\s*(.+)", desc, re.S)
                bits.append("fields: " + short((m.group(1) if m else desc).replace("*", ""), 400))
            else:
                bits.append(short(desc, 400))
            ex = p.get("example") or (sch.get("example") if isinstance(sch, dict) else None)
            if ex:
                bits.append(f"e.g. `{ex}`")
        elif desc:
            bits.append(short(desc, 200))
        lines.append("  - " + " — ".join(bits))
    return lines


def collection_params(spec: Spec, params, experimental: bool) -> dict:
    """Filters (field -> operators), sorters, limit max, query param names for one operation."""
    out: dict = {"query": [], "experimental": experimental}
    for p in params:
        p = spec.res(p)
        if not isinstance(p, dict) or p.get("in") != "query":
            continue
        name, desc = p.get("name", ""), p.get("description", "") or ""
        out["query"].append(name)
        sch = spec.res(p.get("schema", {})) or {}
        if name == "limit" and isinstance(sch, dict) and "maximum" in sch:
            out["limitMax"] = sch["maximum"]
        if name == "filters":
            fields = {}
            for f, ops in re.findall(r"\*\*([\w.\-\[\]]+)\*\*:?\s*\*([^*\n]+)\*", desc):
                fields[f] = [o.strip() for o in ops.split(",") if o.strip()]
            out["filters"] = fields
        if name == "sorters":
            m = re.search(r"following fields:?\s*(.+)", desc, re.S)
            txt = (m.group(1) if m else "").replace("*", "")
            out["sorters"] = [s.strip(" .") for s in re.split(r"[,\n]", txt) if re.fullmatch(r"\s*[\w.\-]+\s*\.?", s)]
    return out


def build_endpoint_refs(specs: Path) -> None:
    sha = git_sha(specs)
    spec = Spec(specs / "dereferenced/deref-sailpoint-api.json")
    by_service: dict[str, list[str]] = {}
    counts: dict[str, int] = {}
    summaries: dict[str, list[str]] = {}
    filt_index: dict[str, dict] = {}
    for path, item in spec.d["paths"].items():
        service = path.strip("/").split("/")[0]
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete") or not isinstance(op, dict):
                continue
            params = list(item.get("parameters", [])) + list(op.get("parameters", []))
            experimental = any(
                isinstance(spec.res(p), dict) and spec.res(p).get("name", "").lower() == "x-sailpoint-experimental"
                for p in params)
            scopes = []
            for sec in op.get("security", []) or []:
                for v in sec.values():
                    scopes.extend(v)
            levels = op.get("x-sailpoint-userLevels") or op.get("x-sailpont-userLevels") or []
            flags = []
            if experimental:
                flags.append("EXPERIMENTAL (header `X-SailPoint-Experimental: true`)")
            if op.get("deprecated"):
                flags.append("DEPRECATED")
            lines = [f"### {method.upper()} {path}", "",
                     f"`{op.get('operationId', '')}` — {op.get('summary', '')}" + (f" — **{', '.join(flags)}**" if flags else ""),
                     "", short(op.get("description", ""), 500), ""]
            if scopes:
                lines.append(f"- Scopes: {', '.join(sorted(set(scopes)))}")
            if levels:
                lines.append(f"- User levels: {', '.join(levels)}")
            pl = param_lines(spec, params)
            if pl:
                lines.append("- Parameters:")
                lines.extend(pl)
            rb = op.get("requestBody")
            if rb:
                rb = spec.res(rb)
                for ctype, c in (rb.get("content") or {}).items():
                    lines.append(f"- Body ({ctype}): {spec.type_name(c.get('schema'))}")
            for code in ("200", "201", "202", "204"):
                r = (op.get("responses") or {}).get(code)
                if r:
                    r = spec.res(r)
                    c = (r.get("content") or {}).get("application/json")
                    lines.append(f"- Returns {code}: {spec.type_name(c.get('schema')) if c else 'no body'}")
                    break
            filt_index[f"{method.upper()} {path}"] = collection_params(spec, params, experimental)
            by_service.setdefault(service, []).append("\n".join(lines))
            counts[service] = counts.get(service, 0) + 1
            summaries.setdefault(service, []).append(f"{method.upper()} {path}")
    scripts = SKILLS / "isc-api/scripts"
    scripts.mkdir(parents=True, exist_ok=True)
    (scripts / "endpoint_params.json").write_text(json.dumps(
        {"_generated": f"tools/build_references.py from sailpoint-oss/api-specs {sha}", "endpoints": filt_index},
        indent=0, sort_keys=True) + "\n")
    dest = SKILLS / "isc-api/references/endpoints"
    for service, ops in by_service.items():
        write(dest / f"{service}.md", f"# `/{service}` endpoints\n\nBase URL: `https://{{tenant}}.api.identitynow.com`\n\n"
              + "\n\n".join(ops), "sailpoint-oss/api-specs dereferenced/deref-sailpoint-api.json", sha)
    idx = ["# Endpoint index (current per-service API)", "",
           "Each service has a file `endpoints/<service>.md` with every operation: scopes, user levels, "
           "query parameters (including the fields and operators allowed in `filters` and `sorters`), body and "
           "response types. Grep this index for a path or keyword, then open the service file.", ""]
    for service in sorted(by_service):
        idx.append(f"## {service} ({counts[service]})")
        idx.extend(f"- {s}" for s in sorted(summaries[service]))
        idx.append("")
    write(dest.parent / "endpoint-index.md", "\n".join(idx), "sailpoint-oss/api-specs", sha)

    # search request body + workflow schemas, generated from the same spec
    build_schema_ref(spec, "search", SKILLS / "isc-search/references/search-request-schema.md", sha)
    build_multi_schema_ref(spec, ["workflowbody", "workflowtrigger", "eventattributes", "scheduledattributes",
                                  "externalattributes", "workflowdefinition", "workflowexecution"],
                           SKILLS / "isc-workflows/references/workflow-api-schemas.md", sha)
    build_multi_schema_ref(spec, ["subscriptionpostrequest", "subscription", "completeinvocationinput",
                                  "testinvocation"],
                           SKILLS / "isc-event-triggers/references/subscription-api-schemas.md", sha)
    build_multi_schema_ref(spec, ["templatedto", "templatevariablesdto", "templatevariable", "preferencesdto",
                                  "sendtestnotificationrequestdto"],
                           SKILLS / "isc-notifications/references/notification-api-schemas.md", sha)


def schema_block(spec: Spec, name: str) -> str:
    comps = spec.d["components"]["schemas"]
    if name not in comps:
        return f"## {name}\n\n(not found in this spec version)\n"
    s = spec.res(comps[name])
    lines = [f"## {name}", "", short(s.get("description", ""), 600), ""]
    req = set(s.get("required", []))
    for k, v in spec.props(s).items():
        vv = spec.res(v)
        t = spec.type_name(v)
        enum = vv.get("enum") if isinstance(vv, dict) else None
        desc = short(vv.get("description", "") if isinstance(vv, dict) else "", 260)
        ex = vv.get("example") if isinstance(vv, dict) else None
        extra = f" One of: {', '.join(str(e) for e in enum if e is not None)}." if enum else ""
        exs = f" Example: `{json.dumps(ex)[:160]}`" if ex not in (None, "", [], {}) else ""
        lines.append(f"- `{k}`{' (required)' if k in req else ''} — {t}. {desc}{extra}{exs}")
    return "\n".join(lines) + "\n"


def build_schema_ref(spec: Spec, name: str, dest: Path, sha: str) -> None:
    write(dest, f"# Schema: {name}\n\n" + schema_block(spec, name), "sailpoint-oss/api-specs", sha)


def build_multi_schema_ref(spec: Spec, names, dest: Path, sha: str) -> None:
    write(dest, "# API schemas\n\n" + "\n".join(schema_block(spec, n) for n in names), "sailpoint-oss/api-specs", sha)


